#define _POSIX_C_SOURCE 200809L
#include "cpm.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>

// Ask Git for the exact 40-character commit hash of a cloned dependency
int get_git_commit(const char *dep_dir, char *out_commit, size_t sz) {
    out_commit[0] = '\0';
    char cmd[512];
    snprintf(cmd, sizeof(cmd), "git -C %s rev-parse HEAD 2>/dev/null", dep_dir);

    FILE *fp = popen(cmd, "r");
    if (!fp) return 0;

    if (fgets(out_commit, sz, fp)) {
        out_commit[strcspn(out_commit, "\r\n")] = '\0';
    }
    pclose(fp);
    return (strlen(out_commit) > 0);
}

// Compute the sha256 checksum of a downloaded file (like a single-header library)
int get_file_sha256(const char *filepath, char *out_sha, size_t sz) {
    out_sha[0] = '\0';
    char cmd[512];
    snprintf(cmd, sizeof(cmd), "sha256sum %s 2>/dev/null", filepath);

    FILE *fp = popen(cmd, "r");
    if (!fp) return 0;

    char line[256];
    if (fgets(line, sizeof(line), fp)) {
        // sha256sum outputs: "<hash>  <filename>"
        char *space = strchr(line, ' ');
        if (space) *space = '\0';
        strncpy(out_sha, line, sz - 1);
        out_sha[sz - 1] = '\0';
    }
    pclose(fp);
    return (strlen(out_sha) > 0);
}

// Query pkg-config for the exact installed version of a system package
int get_pkg_version(const char *pkg_name, char *out_ver, size_t sz) {
    out_ver[0] = '\0';
    char cmd[512];
    snprintf(cmd, sizeof(cmd), "pkg-config --modversion %s 2>/dev/null", pkg_name);

    FILE *fp = popen(cmd, "r");
    if (!fp) return 0;

    if (fgets(out_ver, sz, fp)) {
        out_ver[strcspn(out_ver, "\r\n")] = '\0';
    }
    pclose(fp);
    return (strlen(out_ver) > 0);
}

// Search for a package in the parsed lockfile
const LockedPackage *lockfile_find(const Lockfile *lock, const char *pkg_name) {
    if (!lock) return NULL;
    for (int i = 0; i < lock->package_count; i++) {
        if (strcmp(lock->packages[i].name, pkg_name) == 0) {
            return &lock->packages[i];
        }
    }
    return NULL;
}

// Read cpm.lock if it exists
int lockfile_read(const char *filename, Lockfile *lock) {
    FILE *fp = fopen(filename, "r");
    if (!fp) return -1; // No lockfile yet

    memset(lock, 0, sizeof(Lockfile));
    lock->version = 1;

    char line[1024];
    LockedPackage *current_pkg = NULL;

    while (fgets(line, sizeof(line), fp)) {
        line[strcspn(line, "\r\n")] = '\0';

        char *p = line;
        while (*p && isspace((unsigned char)*p)) p++;
        if (*p == '#' || *p == '\0') continue;

        if (strstr(p, "[[package]]") == p) {
            if (lock->package_count < MAX_DEPS) {
                current_pkg = &lock->packages[lock->package_count++];
                memset(current_pkg, 0, sizeof(LockedPackage));
            } else {
                current_pkg = NULL;
            }
            continue;
        }

        if (!current_pkg) continue;

        char *eq = strchr(p, '=');
        if (!eq) continue;

        *eq = '\0';
        char *key = p;
        char *val = eq + 1;

        trim_whitespace(key);
        trim_whitespace(val);

        if (strcmp(key, "name") == 0) {
            strncpy(current_pkg->name, val, sizeof(current_pkg->name) - 1);
        } else if (strcmp(key, "type") == 0) {
            if (strcmp(val, "git") == 0) current_pkg->type = DEP_TYPE_GIT;
            else if (strcmp(val, "url") == 0) current_pkg->type = DEP_TYPE_URL;
            else current_pkg->type = DEP_TYPE_SYSTEM;
        } else if (strcmp(key, "version") == 0) {
            strncpy(current_pkg->version, val, sizeof(current_pkg->version) - 1);
        } else if (strcmp(key, "source") == 0) {
            strncpy(current_pkg->source, val, sizeof(current_pkg->source) - 1);
        } else if (strcmp(key, "tag") == 0) {
            strncpy(current_pkg->tag, val, sizeof(current_pkg->tag) - 1);
        } else if (strcmp(key, "commit") == 0) {
            strncpy(current_pkg->commit, val, sizeof(current_pkg->commit) - 1);
        } else if (strcmp(key, "checksum") == 0) {
            strncpy(current_pkg->checksum, val, sizeof(current_pkg->checksum) - 1);
        }
    }

    fclose(fp);
    return 0;
}

// Write out cpm.lock so builds can be reproduced across different machines
int lockfile_write(const char *filename, const Lockfile *lock) {
    FILE *fp = fopen(filename, "w");
    if (!fp) {
        perror("fopen cpm.lock");
        return -1;
    }

    fprintf(fp, "# This file is automatically generated by cpm.\n");
    fprintf(fp, "# Commit this file to version control for reproducible builds.\n\n");
    fprintf(fp, "version = %d\n", lock->version ? lock->version : 1);

    for (int i = 0; i < lock->package_count; i++) {
        const LockedPackage *p = &lock->packages[i];
        fprintf(fp, "\n[[package]]\n");
        fprintf(fp, "name = \"%s\"\n", p->name);

        if (p->type == DEP_TYPE_GIT) {
            fprintf(fp, "type = \"git\"\n");
            fprintf(fp, "source = \"%s\"\n", p->source);
            if (p->tag[0]) fprintf(fp, "tag = \"%s\"\n", p->tag);
            if (p->commit[0]) fprintf(fp, "commit = \"%s\"\n", p->commit);
        } else if (p->type == DEP_TYPE_URL) {
            fprintf(fp, "type = \"url\"\n");
            fprintf(fp, "source = \"%s\"\n", p->source);
            if (p->checksum[0]) fprintf(fp, "checksum = \"%s\"\n", p->checksum);
        } else {
            fprintf(fp, "type = \"system\"\n");
            if (p->version[0]) fprintf(fp, "version = \"%s\"\n", p->version);
        }
    }

    fclose(fp);
    return 0;
}
